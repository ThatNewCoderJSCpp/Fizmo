void test_streaming_and_seek() {
    std::vector<std::uint8_t> s = stereo_file();
    AudioBuffer full;
    read_vorbis(s.data(), s.size(), full);
    VorbisReader r;
    std::string err;
    check(r.open(s.data(), s.size(), &err), "VorbisReader opens memory: " + err);
    check(r.is_open() && r.info().frames == 12000 && r.position() == 0, "VorbisReader reports info and starts at 0");
    std::vector<float> got;
    std::vector<float> chunk(2 * 1000);
    std::size_t sizes[] = { 1, 7, 333, 1000, 64, 999 };
    std::size_t k = 0;
    while (true) {
        const std::size_t want = sizes[k++ % 6];
        const std::size_t n = r.read(chunk.data(), want);
        got.insert(got.end(), chunk.begin(), chunk.begin() + static_cast<std::ptrdiff_t>(n * 2));
        if (n == 0) break;
    }
    check(got == full.samples(), "reading in odd chunk sizes gives the same samples as a whole decode");
    check(r.position() == 12000 && r.read(chunk.data(), 10) == 0, "position reaches the end and reads stop");

    std::mt19937 rng(5);
    bool seeks_ok = true;
    std::vector<std::uint64_t> targets = { 0, 1, 2, 127, 128, 1023, 1024, 5000, 11000, 11999, 12000 };
    for (int i = 0; i < 40; ++i) targets.push_back(rng() % 12000);
    for (std::uint64_t t : targets) {
        if (!r.seek(t) || r.position() != t) {
            seeks_ok = false;
            break;
        }
        std::vector<float> buf(2 * 1500);
        const std::size_t n = r.read(buf.data(), 1500);
        const std::size_t want = static_cast<std::size_t>(std::min<std::uint64_t>(1500, 12000 - t));
        if (n != want || !same_samples(buf.data(), full.data() + t * 2, n * 2)) {
            seeks_ok = false;
            std::printf("  seek to %llu read %zu frames\n", static_cast<unsigned long long>(t), n);
            break;
        }
    }
    check(seeks_ok, "seeking is sample-exact anywhere in the file");
    check(r.seek(999999) && r.position() == 12000 && r.read(chunk.data(), 10) == 0, "seeking past the end clamps to the end");
    AudioBuffer appended;
    r.seek(11000);
    check(r.read(appended, 400) == 400 && r.read(appended, 1000) == 600 && appended.frames() == 1000, "read into an AudioBuffer appends frames");
    VorbisReader moved(std::move(r));
    check(moved.is_open() && moved.seek(0) && moved.read(chunk.data(), 5) == 5, "VorbisReader can be moved");
    moved.close();
    check(!moved.is_open() && moved.read(chunk.data(), 5) == 0 && !moved.seek(0), "a closed reader reads nothing");
}

void test_chains_and_streams() {
    std::vector<std::uint8_t> m = mono_file();
    AudioBuffer one;
    read_vorbis(m.data(), m.size(), one);
    std::vector<std::uint8_t> chain = m;
    chain.insert(chain.end(), m.begin(), m.end());
    chain.insert(chain.end(), m.begin(), m.end());
    AudioBuffer b;
    VorbisInfo info;
    std::string err;
    check(read_vorbis(chain.data(), chain.size(), b, &err, &info), "a chained file decodes: " + err);
    bool same = b.frames() == 9000;
    for (std::size_t link = 0; same && link < 3; ++link) same = same_samples(b.data() + link * 3000, one.data(), 3000);
    check(same && info.links == 3 && !info.chain_stopped, "every link of a same-format chain is decoded in full, even with equal serial numbers");
    VorbisReader r;
    r.open(chain.data(), chain.size());
    bool seeks_ok = r.info().frames == 9000;
    const std::uint64_t targets[] = { 2999, 3000, 3001, 6500, 100, 8999, 4500 };
    for (std::uint64_t t : targets) {
        std::vector<float> buf(800);
        if (!seeks_ok || !r.seek(t)) {
            seeks_ok = false;
            break;
        }
        const std::size_t n = r.read(buf.data(), 800);
        const std::size_t want = static_cast<std::size_t>(std::min<std::uint64_t>(800, 9000 - t));
        seeks_ok = n == want && same_samples(buf.data(), b.data() + t, n);
    }
    check(seeks_ok, "seeking across chain links is sample-exact");

    std::vector<std::uint8_t> s = stereo_file();
    std::vector<std::uint8_t> mixed = s;
    mixed.insert(mixed.end(), m.begin(), m.end());
    AudioBuffer mb;
    check(read_vorbis(mixed.data(), mixed.size(), mb, &err, &info), "a chain with a format change opens");
    check(info.chain_stopped && info.links == 1 && mb.frames() == 12000 && mb.channels() == 2, "decoding stops at a link whose format differs, and info says so");

    AudioBuffer ref;
    read_vorbis(s.data(), s.size(), ref);
    OggReader pr;
    pr.open(s.data(), s.size());
    std::vector<OggPage> pages;
    OggPage page;
    while (pr.read_page(page)) pages.push_back(page);
    std::vector<std::uint8_t> muxed;
    std::vector<std::uint8_t> head = make_page(0x7E57, 0, 2, 0, { 42 }, std::vector<std::uint8_t>(42, 0x80));
    muxed.insert(muxed.end(), head.begin(), head.end());
    std::uint32_t seq = 1;
    for (std::size_t i = 0; i < pages.size(); ++i) {
        const std::vector<std::uint8_t> bytes = page_bytes(pages[i]);
        muxed.insert(muxed.end(), bytes.begin(), bytes.end());
        if (i >= 1) {
            const std::vector<std::uint8_t> junk(300 + 50 * i, static_cast<std::uint8_t>(i));
            const std::vector<std::uint8_t> other = make_page(0x7E57, seq++, i + 1 == pages.size() ? 4 : 0, static_cast<std::int64_t>(i), lacing_for(junk.size()), junk);
            muxed.insert(muxed.end(), other.begin(), other.end());
        }
    }
    check(is_ogg_vorbis(muxed.data(), muxed.size()), "is_ogg_vorbis finds Vorbis behind another stream's BOS page");
    AudioBuffer xb;
    check(read_vorbis(muxed.data(), muxed.size(), xb, &err) && xb.samples() == ref.samples(), "a file with another logical stream (e.g. video) multiplexed in still plays its audio exactly");
    VorbisReader xr;
    xr.open(muxed.data(), muxed.size());
    std::vector<float> buf(2 * 500);
    check(xr.seek(7000) && xr.read(buf.data(), 500) == 500 && same_samples(buf.data(), ref.data() + 14000, 1000), "seeking works with a multiplexed foreign stream");
}

void test_damage() {
    std::vector<std::uint8_t> s = stereo_file();
    AudioBuffer full;
    read_vorbis(s.data(), s.size(), full);
    std::string err;
    AudioBuffer b;
    err.clear();
    check(!read_vorbis(s.data(), 0, b, &err) && !err.empty(), "empty input fails with a message");
    err.clear();
    check(!read_vorbis(nullptr, 100, b, &err) && !err.empty(), "null input fails with a message");
    std::vector<std::uint8_t> junk(5000);
    std::mt19937 rng(77);
    for (auto& v : junk) v = static_cast<std::uint8_t>(rng());
    err.clear();
    check(!read_vorbis(junk.data(), junk.size(), b, &err) && !err.empty(), "random bytes fail with a message: " + err);

    bool truncation_ok = true;
    int opened = 0;
    for (std::size_t cut = 0; cut < s.size(); cut += 23) {
        err.clear();
        AudioBuffer t;
        if (read_vorbis(s.data(), cut, t, &err)) {
            ++opened;
            if (t.frames() > 12000 || !same_samples(t.data(), full.data(), t.sample_count())) truncation_ok = false;
        } else if (err.empty()) {
            truncation_ok = false;
        }
    }
    check(truncation_ok, "truncated files never crash, report errors, and decode a correct prefix");
    check(opened > 0, "truncated files that keep their headers still decode");

    OggReader pr;
    pr.open(s.data(), s.size());
    std::vector<OggPage> pages;
    OggPage page;
    while (pr.read_page(page)) pages.push_back(page);
    check(pages.size() == 3 && pages[2].granule == 12000, "the stereo test file has two header pages and one audio page");
    std::vector<std::uint8_t> header_bad = s;
    header_bad[static_cast<std::size_t>(pages[1].offset) + 27 + pages[1].lacing.size() + 3000] ^= 0x01;
    err.clear();
    check(!read_vorbis(header_bad.data(), header_bad.size(), b, &err) && !err.empty(), "a setup header page with a bad CRC fails with a message: " + err);

    std::vector<std::uint8_t> m = mono_file();
    AudioBuffer one;
    read_vorbis(m.data(), m.size(), one);
    std::vector<std::uint8_t> chain = m;
    chain.insert(chain.end(), m.begin(), m.end());
    chain.insert(chain.end(), m.begin(), m.end());
    const std::size_t audio_page = m.size() + 2627 + 27 + 13 + 100;
    chain[audio_page] ^= 0x40;
    OggReader cr;
    cr.open(chain.data(), chain.size());
    std::size_t count = 0;
    while (cr.read_page(page)) ++count;
    check(cr.crc_failures() >= 1 && count == 8, "a corrupted audio page fails its CRC check and is skipped");
    AudioBuffer cb;
    VorbisInfo info;
    bool continued = read_vorbis(chain.data(), chain.size(), cb, &err, &info) && cb.frames() == 6000;
    continued = continued && same_samples(cb.data(), one.data(), 3000) && same_samples(cb.data() + 3000, one.data(), 3000);
    check(continued, "decoding continues exactly past a page with a bad CRC");

    int survived = 0;
    for (int i = 0; i < 400; ++i) {
        std::vector<std::uint8_t> d = (i % 3 == 0) ? surround_file() : (i % 3 == 1 ? stereo_file() : mono_file());
        const int flips = 1 + static_cast<int>(rng() % 6);
        const std::size_t span = i % 2 ? d.size() : std::min<std::size_t>(d.size(), 5000);
        for (int f = 0; f < flips; ++f) d[rng() % span] ^= static_cast<std::uint8_t>(1u << (rng() % 8));
        if (i % 4 != 0) {
            std::size_t pos = 0;
            while (pos + 27 <= d.size()) {
                if (std::memcmp(&d[pos], "OggS", 4) != 0) {
                    ++pos;
                    continue;
                }
                const std::size_t nseg = d[pos + 26];
                if (pos + 27 + nseg > d.size()) break;
                std::size_t body = 0;
                for (std::size_t q = 0; q < nseg; ++q) body += d[pos + 27 + q];
                if (pos + 27 + nseg + body > d.size()) break;
                std::memset(&d[pos + 22], 0, 4);
                detail::put_le32(&d[pos + 22], detail::ogg_crc(&d[pos], 27 + nseg + body));
                pos += 27 + nseg + body;
            }
        }
        VorbisReader vr;
        err.clear();
        if (vr.open(d.data(), d.size(), &err)) {
            std::vector<float> buf(4096 * vr.info().channels);
            std::uint64_t total = 0;
            while (std::size_t n = vr.read(buf.data(), 4096)) {
                total += n;
                if (total > 10000000) break;
            }
            vr.seek(rng() % (vr.info().frames + 1));
            vr.read(buf.data(), 100);
            if (total <= 10000000) ++survived;
        } else if (!err.empty()) {
            ++survived;
        }
    }
    check(survived == 400, "400 randomly damaged files decode or fail cleanly, " + std::to_string(survived) + " did");
}

