void test_ogg_packets() {
    std::mt19937 rng(99);
    std::vector<std::vector<std::uint8_t>> packets;
    std::vector<std::int64_t> granules;
    const std::size_t sizes[] = { 0, 1, 254, 255, 256, 510, 511, 70000, 3, 1000, 255 * 40, 17 };
    for (int round = 0; round < 3; ++round) {
        for (std::size_t sz : sizes) {
            std::vector<std::uint8_t> pk(sz);
            for (auto& b : pk) b = static_cast<std::uint8_t>(rng());
            packets.push_back(pk);
            granules.push_back(static_cast<std::int64_t>(packets.size()) * 100);
        }
    }
    std::vector<std::uint64_t> offsets;
    const std::vector<std::uint8_t> stream = paginate(1234, packets, granules, 17, &offsets);
    OggReader r;
    r.open(stream.data(), stream.size());
    std::vector<OggPacket> got;
    OggPacket p;
    while (r.read_packet(p)) got.push_back(p);
    bool same = got.size() == packets.size();
    for (std::size_t i = 0; same && i < got.size(); ++i) same = got[i].data == packets[i] && got[i].serial == 1234;
    check(same, "packets spanning many pages (lacing and continued pages) are rebuilt exactly");
    bool granule_ok = true;
    for (const OggPacket& q : got) {
        if (q.granule >= 0 && !q.last_on_page) granule_ok = false;
        if (q.last_on_page && q.granule < 0) granule_ok = false;
    }
    check(granule_ok && !got.empty() && got.back().eos && got.front().bos, "granules sit on the last packet completed on each page; bos and eos are flagged");

    std::size_t continued_page = 0;
    OggPage page;
    for (std::size_t i = 0; i < offsets.size(); ++i) {
        if (r.page_at(offsets[i], stream.size(), page) && page.continued() && page.packets_completed() >= 2) {
            continued_page = i;
            break;
        }
    }
    check(continued_page > 0, "the paginated stream has a continued page");
    r.seek(offsets[continued_page]);
    check(r.read_packet(p) && p.after_gap, "after a seek the first packet is flagged after_gap");
    bool found = false;
    for (std::size_t i = 0; i < packets.size(); ++i) {
        if (packets[i] == p.data && i > 0) found = true;
    }
    check(found, "after a seek into a continued page the partial packet is dropped and a whole packet follows");

    std::vector<std::uint8_t> broken = stream;
    broken[static_cast<std::size_t>(offsets[2]) + 40] ^= 0x10;
    OggReader rb;
    rb.open(broken.data(), broken.size());
    std::size_t pages = 0;
    while (rb.read_page(page)) ++pages;
    check(rb.crc_failures() == 1 && pages + 1 == offsets.size(), "a page with a bad CRC is detected and skipped");
    OggReader rc;
    rc.open(broken.data(), broken.size());
    std::size_t count = 0;
    bool gap = false;
    while (rc.read_packet(p)) {
        ++count;
        if (count > 1 && p.after_gap) gap = true;
    }
    check(count < packets.size() && gap, "packets touching a damaged page are dropped and the gap is reported");

    std::vector<std::vector<std::uint8_t>> pa;
    std::vector<std::vector<std::uint8_t>> pb;
    std::vector<std::int64_t> ga;
    std::vector<std::int64_t> gb;
    for (int i = 0; i < 4000; ++i) {
        std::vector<std::uint8_t> x(static_cast<std::size_t>(20 + rng() % 200));
        for (auto& b : x) b = static_cast<std::uint8_t>(rng());
        pa.push_back(x);
        ga.push_back(static_cast<std::int64_t>(i) * 64 + 64);
        x.resize(static_cast<std::size_t>(10 + rng() % 90));
        pb.push_back(x);
        gb.push_back(static_cast<std::int64_t>(i) * 3);
    }
    const std::vector<std::uint8_t> sa = paginate(1, pa, ga, 8);
    const std::vector<std::uint8_t> sb = paginate(2, pb, gb, 8);
    std::vector<std::uint8_t> mux;
    std::vector<std::pair<std::uint64_t, std::int64_t>> a_pages;
    {
        OggReader ra;
        OggReader rbb;
        ra.open(sa.data(), sa.size());
        rbb.open(sb.data(), sb.size());
        OggPage pa_page;
        OggPage pb_page;
        bool more_a = ra.read_page(pa_page);
        bool more_b = rbb.read_page(pb_page);
        while (more_a || more_b) {
            if (more_a) {
                if (pa_page.granule >= 0) a_pages.emplace_back(mux.size(), pa_page.granule);
                const std::vector<std::uint8_t> bytes = page_bytes(pa_page);
                mux.insert(mux.end(), bytes.begin(), bytes.end());
                more_a = ra.read_page(pa_page);
            }
            if (more_b) {
                const std::vector<std::uint8_t> bytes = page_bytes(pb_page);
                mux.insert(mux.end(), bytes.begin(), bytes.end());
                more_b = rbb.read_page(pb_page);
            }
        }
    }
    check(mux.size() > 300000, "the multiplexed bisection test stream is large enough to bisect");
    OggReader rm;
    rm.open(mux.data(), mux.size());
    bool bisect_ok = true;
    const std::int64_t targets[] = { -5, 0, 63, 64, 65, 1000, 77777, 128000, 255999, 256000, 999999 };
    for (std::int64_t t : targets) {
        std::uint64_t want = 0;
        bool want_found = false;
        for (const auto& ap : a_pages) {
            if (ap.second <= t) {
                want = ap.first;
                want_found = true;
            }
        }
        OggPage found_page;
        const bool ok = rm.find_granule(1, t, 0, mux.size(), found_page);
        if (ok != want_found || (ok && (found_page.offset != want || found_page.serial != 1))) bisect_ok = false;
    }
    check(bisect_ok, "bisection finds the last page of a stream at or before a granule, skipping other streams");
    OggPage tail;
    check(rm.last_granule_page(1, 0, mux.size(), tail) && tail.granule == ga.back(), "the last granule of a stream is found from the end");
}

