std::vector<std::uint8_t> bytes_of(const unsigned char* data, std::size_t size) {
    return std::vector<std::uint8_t>(data, data + size);
}

std::vector<std::uint8_t> stereo_file() { return bytes_of(k_stereo_ogg, sizeof(k_stereo_ogg)); }
std::vector<std::uint8_t> mono_file() { return bytes_of(k_mono_ogg, sizeof(k_mono_ogg)); }
std::vector<std::uint8_t> surround_file() { return bytes_of(k_surround_ogg, sizeof(k_surround_ogg)); }

bool near(double a, double b, double tolerance) {
    return std::fabs(a - b) <= tolerance;
}

double channel_rms(const AudioBuffer& b, std::size_t channel) {
    double sum = 0.0;
    for (std::size_t i = 0; i < b.frames(); ++i) sum += double(b.at(i, channel)) * b.at(i, channel);
    return b.frames() ? std::sqrt(sum / b.frames()) : 0.0;
}

double total_rms(const AudioBuffer& b) {
    double sum = 0.0;
    for (float v : b.samples()) sum += double(v) * v;
    return b.sample_count() ? std::sqrt(sum / b.sample_count()) : 0.0;
}

bool same_samples(const float* a, const float* b, std::size_t count) {
    return count == 0 || std::memcmp(a, b, count * sizeof(float)) == 0;
}

std::string tag(const VorbisInfo& info, const std::string& key) {
    for (const auto& t : info.tags) {
        if (t.first == key) return t.second;
    }
    return std::string();
}

std::vector<std::uint8_t> make_page(std::uint32_t serial, std::uint32_t sequence, std::uint8_t flags, std::int64_t granule, const std::vector<std::uint8_t>& lacing, const std::vector<std::uint8_t>& body) {
    std::vector<std::uint8_t> p(27, 0);
    p[0] = 'O';
    p[1] = 'g';
    p[2] = 'g';
    p[3] = 'S';
    p[5] = flags;
    detail::put_le64(&p[6], static_cast<std::uint64_t>(granule));
    detail::put_le32(&p[14], serial);
    detail::put_le32(&p[18], sequence);
    p[26] = static_cast<std::uint8_t>(lacing.size());
    p.insert(p.end(), lacing.begin(), lacing.end());
    p.insert(p.end(), body.begin(), body.end());
    detail::put_le32(&p[22], detail::ogg_crc(p.data(), p.size()));
    return p;
}

std::vector<std::uint8_t> page_bytes(const OggPage& page) {
    return make_page(page.serial, page.sequence, page.flags, page.granule, page.lacing, page.body);
}

std::vector<std::uint8_t> lacing_for(std::size_t size) {
    std::vector<std::uint8_t> l(size / 255, 255);
    l.push_back(static_cast<std::uint8_t>(size % 255));
    return l;
}

std::vector<std::uint8_t> paginate(std::uint32_t serial, const std::vector<std::vector<std::uint8_t>>& packets, const std::vector<std::int64_t>& granules, std::size_t max_segments, std::vector<std::uint64_t>* page_offsets = nullptr) {
    std::vector<std::uint8_t> out;
    std::vector<std::uint8_t> lacing;
    std::vector<std::uint8_t> body;
    std::uint32_t sequence = 0;
    bool continued = false;
    bool first = true;
    std::int64_t granule = -1;
    auto flush = [&](bool last, bool next_continued) {
        std::uint8_t flags = 0;
        if (continued) flags |= 1;
        if (first) flags |= 2;
        if (last) flags |= 4;
        if (page_offsets) page_offsets->push_back(out.size());
        const std::vector<std::uint8_t> p = make_page(serial, sequence++, flags, granule, lacing, body);
        out.insert(out.end(), p.begin(), p.end());
        lacing.clear();
        body.clear();
        first = false;
        granule = -1;
        continued = next_continued;
    };
    for (std::size_t i = 0; i < packets.size(); ++i) {
        const std::vector<std::uint8_t>& pk = packets[i];
        std::size_t pos = 0;
        while (true) {
            if (lacing.size() == max_segments) flush(false, pos > 0);
            const std::size_t n = std::min<std::size_t>(255, pk.size() - pos);
            lacing.push_back(static_cast<std::uint8_t>(n));
            body.insert(body.end(), pk.begin() + static_cast<std::ptrdiff_t>(pos), pk.begin() + static_cast<std::ptrdiff_t>(pos + n));
            pos += n;
            if (n < 255) {
                granule = granules[i];
                break;
            }
        }
    }
    flush(true, false);
    return out;
}

