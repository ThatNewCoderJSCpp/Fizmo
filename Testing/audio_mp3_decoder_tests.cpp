std::vector<std::uint8_t> syncsafe(std::uint32_t n) {
    return { static_cast<std::uint8_t>((n >> 21) & 0x7F), static_cast<std::uint8_t>((n >> 14) & 0x7F), static_cast<std::uint8_t>((n >> 7) & 0x7F), static_cast<std::uint8_t>(n & 0x7F) };
}

std::vector<std::uint8_t> id3_frame(const char* id, int major, std::uint16_t flags, const std::vector<std::uint8_t>& data) {
    std::vector<std::uint8_t> out(id, id + (major == 2 ? 3 : 4));
    const std::uint32_t n = static_cast<std::uint32_t>(data.size());
    if (major == 2) {
        out.push_back(static_cast<std::uint8_t>(n >> 16));
        out.push_back(static_cast<std::uint8_t>(n >> 8));
        out.push_back(static_cast<std::uint8_t>(n));
    } else {
        std::vector<std::uint8_t> s = major == 4 ? syncsafe(n) : std::vector<std::uint8_t>{ static_cast<std::uint8_t>(n >> 24), static_cast<std::uint8_t>(n >> 16), static_cast<std::uint8_t>(n >> 8), static_cast<std::uint8_t>(n) };
        out.insert(out.end(), s.begin(), s.end());
        out.push_back(static_cast<std::uint8_t>(flags >> 8));
        out.push_back(static_cast<std::uint8_t>(flags));
    }
    out.insert(out.end(), data.begin(), data.end());
    return out;
}

std::vector<std::uint8_t> text(int encoding, const std::vector<std::uint8_t>& raw) {
    std::vector<std::uint8_t> out = { static_cast<std::uint8_t>(encoding) };
    out.insert(out.end(), raw.begin(), raw.end());
    return out;
}

std::vector<std::uint8_t> id3_tag(int major, std::uint8_t flags, const std::vector<std::uint8_t>& body) {
    std::vector<std::uint8_t> out = { 'I', 'D', '3', static_cast<std::uint8_t>(major), 0, flags };
    std::vector<std::uint8_t> s = syncsafe(static_cast<std::uint32_t>(body.size()));
    out.insert(out.end(), s.begin(), s.end());
    out.insert(out.end(), body.begin(), body.end());
    return out;
}

