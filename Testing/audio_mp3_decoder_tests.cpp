const Reference* find_ref(const char* name) {
    for (const Reference& r : k_refs) {
        if (std::strcmp(r.name, name) == 0) return &r;
    }
    return nullptr;
}

std::vector<std::uint8_t> bytes_of(const Reference& r) {
    return std::vector<std::uint8_t>(r.data, r.data + r.size);
}

std::string tag_value(const Mp3Info& info, const std::string& key) {
    for (const auto& kv : info.tags) {
        if (kv.first == key) return kv.second;
    }
    return std::string();
}

bool all_finite(const AudioBuffer& b) {
    for (float v : b.samples()) {
        if (!std::isfinite(v)) return false;
    }
    return true;
}

bool same_samples(const float* a, const float* b, std::size_t n) {
    return n == 0 || std::memcmp(a, b, n * sizeof(float)) == 0;
}

std::uint32_t lcg(std::uint32_t& state) {
    state = state * 1664525u + 1013904223u;
    return state >> 8;
}

void test_reference(const Reference& r) {
    const std::string name = std::string("file ") + r.name + ": ";
    check(is_mp3(r.data, r.size), name + "is_mp3 recognises it");
    AudioBuffer out;
    std::string error;
    Mp3Info info;
    const bool ok = read_mp3(r.data, r.size, out, &error, &info);
    check(ok, name + "decodes (" + error + ")");
    if (!ok) return;
    check(info.sample_rate == r.rate, name + "sample rate");
    check(info.channels == r.channels && out.channels() == r.channels, name + "channel count");
    check(out.sample_rate() == r.rate, name + "buffer sample rate");
    check(info.frames == r.frames, name + "info frame count " + std::to_string(info.frames) + " vs " + std::to_string(r.frames));
    check(out.frames() == r.frames, name + "decoded frame count " + std::to_string(out.frames()) + " vs " + std::to_string(r.frames));
    check(info.mpeg_version == r.version, name + "MPEG version");
    check(info.layer == r.layer, name + "layer");
    check(info.vbr == r.vbr, name + "VBR flag");
    if (r.vbr) check(info.bitrate_kbps > 30 && info.bitrate_kbps < 80, name + "average bitrate is plausible");
    else check(info.bitrate_kbps == r.bitrate, name + "bitrate");
    check(info.encoder_delay == r.delay, name + "encoder delay");
    check(info.encoder_padding == r.padding, name + "encoder padding");
    if (out.frames() != r.frames) return;
    check(all_finite(out), name + "all samples are finite");
    const std::size_t ch = r.channels;
    for (std::size_t c = 0; c < ch; ++c) {
        double sum = 0.0;
        for (std::size_t i = 0; i < out.frames(); ++i) sum += static_cast<double>(out.at(i, c)) * out.at(i, c);
        const double rms = std::sqrt(sum / static_cast<double>(out.frames()));
        check(std::fabs(rms - r.rms[c]) <= 1e-5 + 1e-4 * r.rms[c], name + "RMS of channel " + std::to_string(c));
    }
    double worst = 0.0;
    for (int i = 0; i < 12; ++i) worst = std::max(worst, static_cast<double>(std::fabs(out.data()[r.probe_index[i]] - r.probe_value[i])));
    check(worst < 2e-5, name + "probe samples match the reference decoder (worst " + std::to_string(worst) + ")");
    const std::size_t total = out.sample_count();
    std::size_t start = 0;
    bool blocks_ok = true;
    for (int b = 0; b < 8; ++b) {
        const std::size_t len = total / 8 + (static_cast<std::size_t>(b) < total % 8 ? 1u : 0u);
        double sum = 0.0;
        for (std::size_t i = start; i < start + len; ++i) sum += static_cast<double>(out.data()[i]) * out.data()[i];
        const double rms = std::sqrt(sum / static_cast<double>(len));
        if (std::fabs(rms - r.block_rms[b]) > 1e-5 + 1e-4 * r.block_rms[b]) blocks_ok = false;
        start += len;
    }
    check(blocks_ok, name + "block RMS profile matches the reference decoder");
}

void test_streaming(const Reference& r) {
    const std::string name = std::string("stream ") + r.name + ": ";
    AudioBuffer full;
    if (!read_mp3(r.data, r.size, full)) {
        check(false, name + "reference decode");
        return;
    }
    Mp3Reader reader;
    std::string error;
    check(reader.open(r.data, r.size, &error), name + "opens");
    check(reader.is_open(), name + "is_open");
    std::vector<float> got;
    std::vector<float> chunk(333 * 2);
    std::size_t n = 0;
    bool position_ok = true;
    while ((n = reader.read(chunk.data(), 333)) > 0) {
        got.insert(got.end(), chunk.begin(), chunk.begin() + static_cast<std::ptrdiff_t>(n * r.channels));
        if (reader.position() != got.size() / r.channels) position_ok = false;
    }
    check(position_ok, name + "position advances with reads");
    check(got.size() == full.sample_count() && same_samples(got.data(), full.data(), got.size()), name + "chunked reads equal a whole decode");
    check(reader.read(chunk.data(), 10) == 0, name + "read at the end returns nothing");
    AudioBuffer via;
    reader.seek(0);
    reader.read(via, 100);
    reader.read(via, 50);
    check(via.frames() == std::min<std::size_t>(150, full.frames()) && via.channels() == r.channels, name + "AudioBuffer reads append");
    check(same_samples(via.data(), full.data(), via.sample_count()), name + "AudioBuffer reads hold the right samples");
    reader.close();
    check(!reader.is_open() && reader.read(chunk.data(), 10) == 0, name + "closed reader reads nothing");
}

void test_seek(const Reference& r) {
    const std::string name = std::string("seek ") + r.name + ": ";
    AudioBuffer full;
    if (!read_mp3(r.data, r.size, full)) {
        check(false, name + "reference decode");
        return;
    }
    Mp3Reader reader;
    reader.open(r.data, r.size);
    const std::uint64_t total = full.frames();
    std::vector<std::uint64_t> targets = { 0, 1, 2, 529, 575, 576, 577, 1151, 1152, 1153, total / 3, total / 2, total - 700, total - 1, total };
    std::uint32_t state = 12345u + static_cast<std::uint32_t>(r.size);
    for (int i = 0; i < 12; ++i) targets.push_back(lcg(state) % (total + 1));
    targets.push_back(total + 1000);
    std::vector<float> buf(700 * 2);
    bool exact = true;
    bool positions = true;
    for (std::uint64_t t : targets) {
        if (t > total + 1000) continue;
        check(reader.seek(t), name + "seek returns true");
        const std::uint64_t clamped = std::min(t, total);
        if (reader.position() != clamped) positions = false;
        const std::size_t want = static_cast<std::size_t>(std::min<std::uint64_t>(700, total - clamped));
        const std::size_t got = reader.read(buf.data(), 700);
        if (got != want) exact = false;
        if (!same_samples(buf.data(), full.frame(static_cast<std::size_t>(clamped)), got * r.channels)) exact = false;
        if (reader.position() != clamped + got) positions = false;
    }
    check(exact, name + "seeking is sample-accurate and bit-exact");
    check(positions, name + "position is right after seeks");
    reader.seek(total / 2);
    reader.seek(0);
    const std::size_t got = reader.read(buf.data(), 700);
    check(got == std::min<std::size_t>(700, static_cast<std::size_t>(total)) && same_samples(buf.data(), full.data(), got * r.channels), name + "seeking back to the start");
}

