std::string frame_md5(const VideoFrame& f) {
    Md5 m;
    for (int p = 0; p < plane_count(f.format); ++p) {
        for (std::uint32_t y = 0; y < f.plane_height(p); ++y) m.update(f.plane(p) + f.stride[p] * y, f.plane_width(p) * static_cast<std::uint32_t>(bytes_per_sample(f.format)));
    }
    return m.hex();
}

std::vector<std::vector<std::uint8_t>> access_units(const std::uint8_t* data, std::size_t size) {
    std::vector<std::vector<std::uint8_t>> out;
    H264FileReader reader;
    if (!reader.open(data, size)) return out;
    std::vector<std::uint8_t> au;
    while (reader.read(au)) out.push_back(au);
    return out;
}

struct NalRef {
    std::size_t offset;
    std::size_t size;
};

std::vector<NalRef> split_nals(const std::vector<std::uint8_t>& d) {
    std::vector<NalRef> out;
    std::size_t i = 0;
    std::size_t start = d.size();
    while (i + 3 <= d.size()) {
        if (d[i] == 0 && d[i + 1] == 0 && d[i + 2] == 1) {
            if (start < d.size()) {
                std::size_t end = i;
                while (end > start && d[end - 1] == 0) --end;
                out.push_back(NalRef{start, end - start});
            }
            i += 3;
            start = i;
        } else {
            ++i;
        }
    }
    if (start < d.size()) out.push_back(NalRef{start, d.size() - start});
    return out;
}

struct Decoded {
    std::vector<std::string> md5;
    std::vector<double> pts;
    std::vector<VideoFrame> frames;
    bool ok = true;
};

void drain(H264Decoder& dec, Decoded& out, bool keep) {
    VideoFrame f;
    while (dec.receive(f)) {
        out.md5.push_back(frame_md5(f));
        out.pts.push_back(f.pts);
        if (keep) out.frames.push_back(f);
    }
}

Decoded decode_annexb(const StreamCase& s, bool keep = false) {
    Decoded out;
    H264Decoder dec;
    dec.open_annexb();
    auto aus = access_units(s.data, s.size);
    for (std::size_t i = 0; i < aus.size(); ++i) {
        if (!dec.decode(aus[i].data(), aus[i].size(), static_cast<double>(i))) out.ok = false;
        drain(dec, out, keep);
    }
    dec.flush();
    drain(dec, out, keep);
    return out;
}

bool make_avcc(const StreamCase& s, int length_size, std::vector<std::uint8_t>& config, std::vector<std::vector<std::uint8_t>>& packets) {
    auto aus = access_units(s.data, s.size);
    std::vector<std::uint8_t> sps;
    std::vector<std::uint8_t> pps;
    packets.clear();
    for (const auto& au : aus) {
        std::vector<std::uint8_t> pkt;
        for (const NalRef& n : split_nals(au)) {
            int type = au[n.offset] & 31;
            if (type == 7 && sps.empty()) sps.assign(au.begin() + static_cast<std::ptrdiff_t>(n.offset), au.begin() + static_cast<std::ptrdiff_t>(n.offset + n.size));
            if (type == 8 && pps.empty()) pps.assign(au.begin() + static_cast<std::ptrdiff_t>(n.offset), au.begin() + static_cast<std::ptrdiff_t>(n.offset + n.size));
            if (type == 7 || type == 8 || type == 9) continue;
            for (int b = length_size - 1; b >= 0; --b) pkt.push_back(static_cast<std::uint8_t>(n.size >> (8 * b)));
            pkt.insert(pkt.end(), au.begin() + static_cast<std::ptrdiff_t>(n.offset), au.begin() + static_cast<std::ptrdiff_t>(n.offset + n.size));
        }
        packets.push_back(pkt);
    }
    if (sps.size() < 4 || pps.empty()) return false;
    config = {1, sps[1], sps[2], sps[3], static_cast<std::uint8_t>(0xFC | (length_size - 1)), 0xE1};
    config.push_back(static_cast<std::uint8_t>(sps.size() >> 8));
    config.push_back(static_cast<std::uint8_t>(sps.size()));
    config.insert(config.end(), sps.begin(), sps.end());
    config.push_back(1);
    config.push_back(static_cast<std::uint8_t>(pps.size() >> 8));
    config.push_back(static_cast<std::uint8_t>(pps.size()));
    config.insert(config.end(), pps.begin(), pps.end());
    return true;
}

Decoded decode_avcc(const StreamCase& s, int length_size) {
    Decoded out;
    std::vector<std::uint8_t> config;
    std::vector<std::vector<std::uint8_t>> packets;
    if (!make_avcc(s, length_size, config, packets)) {
        out.ok = false;
        return out;
    }
    H264Decoder dec;
    std::string err;
    if (!dec.open(config.data(), config.size(), &err)) {
        out.ok = false;
        return out;
    }
    for (std::size_t i = 0; i < packets.size(); ++i) {
        if (!dec.decode(packets[i].data(), packets[i].size(), static_cast<double>(i) * 0.04, &err)) out.ok = false;
        drain(dec, out, false);
    }
    dec.flush();
    drain(dec, out, false);
    return out;
}

bool md5_match(const StreamCase& s, const Decoded& d) {
    if (static_cast<int>(d.md5.size()) != s.frames) return false;
    for (int i = 0; i < s.frames; ++i) {
        if (d.md5[static_cast<std::size_t>(i)] != s.md5[i]) return false;
    }
    return true;
}

bool order_match(const StreamCase& s, const Decoded& d, double scale) {
    if (static_cast<int>(d.pts.size()) != s.frames) return false;
    for (int i = 0; i < s.frames; ++i) {
        if (std::fabs(d.pts[static_cast<std::size_t>(i)] - s.order[i] * scale) > 1e-9) return false;
    }
    return true;
}

void test_conformance() {
    for (const StreamCase& s : k_streams) {
        std::string name = s.name;
        Decoded a = decode_annexb(s, true);
        check(a.ok, name + ": Annex B stream decodes without errors");
        check(md5_match(s, a), name + ": every frame is bit-exact with the reference decoder (" + std::to_string(a.md5.size()) + " frames)");
        check(order_match(s, a, 1.0), name + ": frames come out in display order with their own timestamps");
        bool dims = !a.frames.empty();
        for (const VideoFrame& f : a.frames) {
            if (f.width != s.width || f.height != s.height) dims = false;
        }
        check(dims, name + ": cropped size is " + std::to_string(s.width) + "x" + std::to_string(s.height));
        check(!a.frames.empty() && a.frames[0].keyframe, name + ": first frame is a keyframe");
        Decoded b = decode_avcc(s, 4);
        check(b.ok && md5_match(s, b), name + ": avcC with 4-byte lengths is bit-exact");
        check(order_match(s, b, 0.04), name + ": avcC timestamps are reordered correctly");
    }
}

