inline void bfly(std::int32_t& ta, std::int32_t& tb, int c, int s, int flip) {
    const std::int64_t x = static_cast<std::int64_t>(ta) * c - static_cast<std::int64_t>(tb) * s;
    const std::int64_t y = static_cast<std::int64_t>(ta) * s + static_cast<std::int64_t>(tb) * c;
    const std::int32_t rx = static_cast<std::int32_t>((x + 2048) >> 12);
    const std::int32_t ry = static_cast<std::int32_t>((y + 2048) >> 12);
    if (flip) {
        ta = ry;
        tb = rx;
    } else {
        ta = rx;
        tb = ry;
    }
}

inline void hada(std::int32_t& ta, std::int32_t& tb, std::int64_t lo, std::int64_t hi) {
    const std::int64_t x = ta;
    const std::int64_t y = tb;
    std::int64_t s = x + y;
    std::int64_t d = x - y;
    s = s < lo ? lo : (s > hi ? hi : s);
    d = d < lo ? lo : (d > hi ? hi : d);
    ta = static_cast<std::int32_t>(s);
    tb = static_cast<std::int32_t>(d);
}

