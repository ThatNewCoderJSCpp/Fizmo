int celt_log2_frac(std::uint32_t v, int frac) noexcept {
    if (v == 0) return 0;
    const int l = ilog(v);
    if ((v & (v - 1)) == 0) return (l - 1) << frac;
    std::uint64_t m = l > 16 ? ((static_cast<std::uint64_t>(v) - 1) >> (l - 16)) + 1 : static_cast<std::uint64_t>(v) << (16 - l);
    int result = (l - 1) << frac;
    for (int e = frac; e >= 0; --e) {
        const std::uint64_t b = m >> 16;
        result += static_cast<int>(b) << e;
        m = (m + b) >> b;
        m = (m * m + 32767) >> 15;
    }
    if (m > 32768) ++result;
    return result;
}

int pulses_of(int q) noexcept {
    if (q < 8) return q;
    return (8 + (q & 7)) << ((q >> 3) - 1);
}

